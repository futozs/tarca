export function isOneOf<T extends string>(values: readonly T[], value: unknown): value is T {
  return typeof value === 'string' && values.some((allowed) => allowed === value)
}

export function toVatCode<T extends string>(values: readonly T[], vat: number | string): T {
  const code = typeof vat === 'number' ? `${String(vat).replace('.', ',')}%` : vat
  if (isOneOf(values, code)) return code
  throw new RangeError(
    `Ismeretlen áfakulcs: ${String(vat)}. A szám a Billingo kódjára alakul (27 → '27%', 5.5 → '5,5%'), és a kódnak ezek egyike kell legyen: ${values.join(', ')}.`,
  )
}
